/**
 * Bakes each world's floor-tier scene into one small WebP per phase of the day, for phones that
 * draw the `floor` tier: they show a picture (expo-image, no Skia canvas) under a few CSS-moved
 * overlays instead of drawing the still layers themselves. Writes the pictures and the generated
 * index the app registers at start. Run: pnpm scene:bake
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import React from 'react';

const require = createRequire(import.meta.url);
(globalThis as { React?: unknown }).React = React;

/** One representative minute inside each phase. */
const PHASE_MINUTES = {
  predawn: 300,
  dawn: 420,
  morning: 630,
  afternoon: 870,
  dusk: 1110,
  night: 1320,
} as const;

/** Upright pictures for phones held normally, wide ones for phones on their side and tablets. */
const FRAMES = [
  { suffix: '', W: 432, H: 936 },
  { suffix: '-wide', W: 936, H: 432 },
] as const;
const QUALITY = 62;

async function main() {
  const root = resolve(import.meta.dirname, '../..');
  const outDir = join(root, 'apps/gurudevi-mobile/src/assets/floors');
  const indexFile = join(root, 'apps/gurudevi-mobile/src/generated/floorPictures.ts');
  mkdirSync(outDir, { recursive: true });
  mkdirSync(join(root, 'apps/gurudevi-mobile/src/generated'), { recursive: true });

  const besideSkia = createRequire(require.resolve('react-native-skia/package.json'));
  const CanvasKitInit = besideSkia('canvaskit-wasm/bin/full/canvaskit.js');
  (globalThis as { CanvasKit?: unknown }).CanvasKit = await CanvasKitInit();
  const headless = await import('react-native-skia');
  const { experienceOf } = await import('../../packages/core/src/verger/experience');
  const scene = await import('../../packages/ui/src/theme/scene/index');
  const { ArtStill } = await import('../../packages/ui/src/components/native/Stage/ArtStill');
  const { resolveWorld } = await import('../../packages/ui/src/theme/resolve');

  const budget = experienceOf({ levels: {}, capacityClass: 'high' }, { fidelity: 'auto' });
  const blocks: string[] = [];
  let total = 0;
  for (const { suffix, W, H } of FRAMES) {
    const entries: string[] = [];
    for (const worldId of Object.keys(scene.WORLD_ART)) {
      const phases: string[] = [];
      for (const [phase, minute] of Object.entries(PHASE_MINUTES)) {
        const world = resolveWorld(worldId as never, phase as never, 'light');
        const s = scene.resolveScene({
          now: new Date(2026, 10, 10),
          minute,
          weather: 'clear',
          world: { id: worldId, glow: world.tokens.glow },
          room: 'self',
          presence: 'full',
          budget,
        });
        const art = scene.sceneArtOf(worldId, {
          width: W,
          height: H,
          scene: s,
          tokens: world.tokens,
        });
        if (!art) continue;
        const surface = headless.makeOffscreenSurface(W, H);
        const image = await headless.drawOffscreen(
          surface,
          React.createElement(ArtStill, { layers: art.layers, tier: 'floor' }),
        );
        const bytes = await image.encodeToBytes(headless.ImageFormat.WEBP, QUALITY);
        const name = `${worldId}-${phase}${suffix}.webp`;
        writeFileSync(join(outDir, name), bytes);
        total += bytes.length;
        phases.push(`    ${phase}: require('../assets/floors/${name}'),`);
        console.log(name, `${Math.round(bytes.length / 1024)} KB`);
      }
      if (phases.length) entries.push(`  ${worldId}: {\n${phases.join('\n')}\n  },`);
    }
    const constName = suffix ? 'FLOOR_PICTURES_WIDE' : 'FLOOR_PICTURES';
    blocks.push(`export const ${constName}: FloorPictures = {\n${entries.join('\n')}\n};\n`);
  }
  writeFileSync(
    indexFile,
    `// Generated by scripts/scene-shots/bake.tsx (pnpm scene:bake). Do not edit.\n` +
      `/* eslint-disable */\n` +
      `import type { FloorPictures } from '@repo/ui/components/native';\n\n` +
      blocks.join('\n'),
  );
  console.log(`total ${Math.round(total / 1024)} KB`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
