/**
 * Polymath - Growth Signal Generator
 *
 * Generates growthSignals.generated.ts from growthSignals.schema.json
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const SCHEMA_PATH = path.resolve(__dirname, '../packages/core/src/api/growthSignals.schema.json');
const OUTPUT_PATH = path.resolve(__dirname, '../packages/core/src/api/growthSignals.generated.ts');

function generate() {
  if (!fs.existsSync(SCHEMA_PATH)) {
    console.error(`❌ Schema not found at ${SCHEMA_PATH}`);
    process.exit(1);
  }

  const { signals } = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));

  const signalTypes = signals.map((s) => `    | '${s.id}'`).join('\n');
  const signalMapEntries = signals.map((s) => `    ${s.id}: '${s.dimension}',`).join('\n');

  const content = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY
 * Generated by scripts/generate-growth-signals.mjs
 */

import { GrowthDimension } from './userGrowthState';

/** All semantic signal types derived from growthSignals.schema.json */
export type GrowthSignalType =
${signalTypes};

/** Canonical mapping of every growth signal to its Bhumi dimension */
export const GROWTH_SIGNAL_MAP: Record<GrowthSignalType, GrowthDimension> = {
${signalMapEntries}
};
`;

  fs.writeFileSync(OUTPUT_PATH, content);
  console.log(`✅ Generated ${OUTPUT_PATH}`);
}

generate();
