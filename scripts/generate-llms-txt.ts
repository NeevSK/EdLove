#!/usr/bin/env node
/**
 * Docs7-style llms.txt generator
 * Generates `apps/gurudevi-mobile/docs/llms.txt` from INDEX.md + docs-sop.md
 * Agent-side only — no runtime deps, no platform buy.
 */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(__dirname, '..');
const INDEX_PATH = resolve(PROJECT_ROOT, 'apps', 'gurudevi-mobile', 'docs', 'INDEX.md');
const OUTPUT_PATH = resolve(PROJECT_ROOT, 'apps', 'gurudevi-mobile', 'docs', 'llms.txt');

function parseIndex(
  indexContent: string,
): Array<{ title: string; path: string; whenToRead: string; category: string }> {
  const entries: Array<{ title: string; path: string; whenToRead: string; category: string }> = [];
  let currentCategory = 'Uncategorized';

  const lines = indexContent.split('\n');

  for (const line of lines) {
    // Category headers (## ...)
    const catMatch = line.match(/^##\s+(.+)$/);
    if (catMatch) {
      currentCategory = catMatch[1].trim();
      continue;
    }

    // Numbered list with em-dash: `1. [Title](./path.md) — description`
    const numberedMatch = line.match(/^\s*\d+\.\s+\[(.+?)\]\((\.[^)]+)\)\s*[—-]\s*(.+)$/);
    if (numberedMatch) {
      const [, title, path, description] = numberedMatch;
      entries.push({
        title: title.trim(),
        path: path.replace(/^\.\//, ''),
        whenToRead: description.trim(),
        category: currentCategory,
      });
      continue;
    }

    // Bullet list with em-dash: `- [Title](./path.md) — description`
    const bulletMatch = line.match(/^\s*[*+-]\s+\[(.+?)\]\((\.[^)]+)\)\s*[—-]\s*(.+)$/);
    if (bulletMatch) {
      const [, title, path, description] = bulletMatch;
      entries.push({
        title: title.trim(),
        path: path.replace(/^\.\//, ''),
        whenToRead: description.trim(),
        category: currentCategory,
      });
      continue;
    }

    // Table rows: `| **date** | [Title](./path.md) | Category | Status | Summary |`
    const tableMatch = line.match(
      /^\|\s*\*\*.+?\*\*\s*\|\s*\[(.+?)\]\((\.[^)]+)\)\s*\|.+?\|\s*.+?\s*\|\s*(.+?)\s*\|$/,
    );
    if (tableMatch) {
      const [, title, path, description] = tableMatch;
      entries.push({
        title: title.trim(),
        path: path.replace(/^\.\//, ''),
        whenToRead: description.trim(),
        category: currentCategory,
      });
      continue;
    }

    // Pipe format: `| Title | ./path.md | ...`
    const pipeMatch = line.match(/^\|\s*\[(.+?)\]\((\.[^)]+)\)\s*\|\s*(.+?)\s*\|/);
    if (pipeMatch) {
      const [, title, path, description] = pipeMatch;
      entries.push({
        title: title.trim(),
        path: path.replace(/^\.\//, ''),
        whenToRead: description.trim(),
        category: currentCategory,
      });
      continue;
    }

    // Simple markdown links without description (numbered or bullet)
    const simpleNumberedMatch = line.match(/^\s*\d+\.\s+\[(.+?)\]\((\.[^)]+)\)\s*$/);
    if (simpleNumberedMatch) {
      const [, title, path] = simpleNumberedMatch;
      entries.push({
        title: title.trim(),
        path: path.replace(/^\.\//, ''),
        whenToRead: 'Reference documentation',
        category: currentCategory,
      });
      continue;
    }

    const simpleBulletMatch = line.match(/^\s*[*+-]\s+\[(.+?)\]\((\.[^)]+)\)\s*$/);
    if (simpleBulletMatch) {
      const [, title, path] = simpleBulletMatch;
      entries.push({
        title: title.trim(),
        path: path.replace(/^\.\//, ''),
        whenToRead: 'Reference documentation',
        category: currentCategory,
      });
    }
  }

  return entries;
}

function generateLlmTxt(
  entries: Array<{ title: string; path: string; whenToRead: string; category: string }>,
): string {
  const gitSha =
    process.env.GITHUB_SHA ||
    execSync('git rev-parse HEAD', { encoding: 'utf8' }).trim().slice(0, 7);
  const date = new Date().toISOString().split('T')[0];

  const lines = [
    `# Gurudevi Mobile Documentation Index (llms.txt)`,
    `# Generated: ${date} | Git SHA: ${gitSha}`,
    `# Source: apps/gurudevi-mobile/docs/INDEX.md + docs-sop.md`,
    `# This file follows the Docs7 llms.txt pattern — one line per document.`,
    ``,
  ];

  let currentCat = '';
  for (const entry of entries) {
    if (entry.category !== currentCat) {
      currentCat = entry.category;
      lines.push(`## ${currentCat}`);
      lines.push(``);
    }
    lines.push(`- [${entry.title}](${entry.path}) — ${entry.whenToRead}`);
  }

  lines.push(``);
  lines.push(`---`);
  lines.push(`*Total: ${entries.length} documents*`);
  lines.push(`*Generated by scripts/generate-llms-txt.ts — run to refresh*`);

  return lines.join('\n');
}

function main() {
  const indexContent = readFileSync(INDEX_PATH, 'utf8');
  const entries = parseIndex(indexContent);
  const output = generateLlmTxt(entries);
  writeFileSync(OUTPUT_PATH, output, 'utf8');
  console.log(`✅ Generated llms.txt with ${entries.length} entries → ${OUTPUT_PATH}`);
}

main();
