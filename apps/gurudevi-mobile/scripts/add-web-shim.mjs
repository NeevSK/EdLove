import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PROJECT_ROOT = path.resolve(__dirname, '..');
const METRO_CONFIG_PATH = path.join(PROJECT_ROOT, 'metro.config.js');
const SHIMS_DIR = path.join(PROJECT_ROOT, 'src/shims');

const packageName = process.argv[2];

if (!packageName) {
    console.error('❌ Please specify a package name: `node scripts/add-web-shim.js <package-name>`');
    process.exit(1);
}

const shimFileName = `${packageName.split('/').pop()}-web.js`;
const shimFilePath = path.join(SHIMS_DIR, shimFileName);

// 1. Create the shim file if it doesn't exist
if (!fs.existsSync(shimFilePath)) {
    const defaultShimContent = `/**
 * Web shim for ${packageName}
 * 
 * Auto-generated by add-web-shim.mjs.
 * This shim uses a Proxy by default to help you identify missing methods at runtime.
 */

const noop = () => {};

const proxy = new Proxy({}, {
    get: (target, prop) => {
        if (prop === 'default' || prop === '__esModule') return proxy;
        console.warn(\`⚠️  [Web Shim] Accessing unimplemented property '\${prop.toString()}' on shim for '${packageName}'.\`);
        return noop;
    }
});

export default proxy;
`;
    fs.writeFileSync(shimFilePath, defaultShimContent);
    console.log(`✅ Created shim: src/shims/${shimFileName}`);
} else {
    console.log(`ℹ️  Shim already exists: src/shims/${shimFileName}`);
}

// 2. Update metro.config.js
let metroConfig = fs.readFileSync(METRO_CONFIG_PATH, 'utf8');

if (metroConfig.includes(`'${packageName}':`)) {
    console.log(`ℹ️  Package '${packageName}' is already in WEB_SHIMS.`);
} else {
    const shimEntry = `    '${packageName}': path.resolve(projectRoot, 'src/shims/${shimFileName}'),\n`;
    
    // Find the end of the WEB_SHIMS object (before the last bracket)
    const shimEndIndex = metroConfig.indexOf('};', metroConfig.indexOf('const WEB_SHIMS = {'));
    
    if (shimEndIndex !== -1) {
        metroConfig = metroConfig.slice(0, shimEndIndex) + shimEntry + metroConfig.slice(shimEndIndex);
        fs.writeFileSync(METRO_CONFIG_PATH, metroConfig);
        console.log(`✅ Added '${packageName}' to metro.config.js WEB_SHIMS.`);
    } else {
        console.error('❌ Could not find WEB_SHIMS block in metro.config.js');
        process.exit(1);
    }
}

console.log(`\n🎉 Web shim for '${packageName}' is ready!`);
console.log('💡 Tip: Edit the shim file to match the specific methods your app uses.');
