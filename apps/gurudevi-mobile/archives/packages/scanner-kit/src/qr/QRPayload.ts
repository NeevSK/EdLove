/**
 * Canonical QR Payload Types — Gurudevi Ecosystem
 *
 * All QR codes encode: gurudevi://qr?v=1&action=<action>&...params
 * Legacy formats (join-class:UUID, join-group:UUID, bare UUID) are also handled
 * by QRResolver for backward compatibility with deployed QR codes.
 */

export const QR_VERSION = 1 as const;

export type QRAction =
  | 'join_school'
  | 'join_class'
  | 'join_group'
  | 'claim_invite'
  | 'user_invite'
  | 'thuthimal_gift';

/** Unified discriminated union for all QR payloads in the Gurudevi ecosystem */
export type QRPayload =
  | JoinSchoolPayload
  | JoinClassPayload
  | JoinGroupPayload
  | ClaimInvitePayload
  | UserInvitePayload
  | ThuthimalGiftPayload;

/**
 * Scanning joins the school AND its auto-created community group in one action.
 * Replaces the two separate QRs (bare school UUID + join-group:) that existed before.
 */
export interface JoinSchoolPayload {
  v: typeof QR_VERSION;
  action: 'join_school';
  school_id: string;
  /** ID of the school's auto-created community group */
  group_id: string;
  /** Handle of the school (e.g. @myschool) */
  handle?: string;
}

/** Teacher or student joins a specific classroom via QR scan */
export interface JoinClassPayload {
  v: typeof QR_VERSION;
  action: 'join_class';
  classroom_id: string;
  /** Handle of the classroom (e.g. @myclass) */
  handle?: string;
}

/** Join a community group directly (standalone group QR) */
export interface JoinGroupPayload {
  v: typeof QR_VERSION;
  action: 'join_group';
  group_id: string;
  /** Handle of the group (e.g. @mygroup) */
  handle?: string;
}

/** Claim a role-specific school invite code (generated by principal in InviteManager) */
export interface ClaimInvitePayload {
  v: typeof QR_VERSION;
  action: 'claim_invite';
  invite_code: string;
  school_id: string;
  /** UserRole string e.g. 'teacher' | 'student' | 'section_head' | 'grade_head' */
  role: string;
}

/** Personal referral QR shown on user identity card back — tracks inviter attribution */
export interface UserInvitePayload {
  v: typeof QR_VERSION;
  action: 'user_invite';
  inviter_id: string;
  /** UserRole string of the person sharing their QR */
  inviter_role: string;
  /** Username of the inviter (e.g. @username) */
  username?: string;
}

/**
 * One-time Thuthimal (තුතිමල් — Flower of Gratitude) Pro subscription gift.
 * The gift_token is a UUID stored in thuthimal_gifts table, consumed once on claim.
 */
export interface ThuthimalGiftPayload {
  v: typeof QR_VERSION;
  action: 'thuthimal_gift';
  /** UUID token from thuthimal_gifts.gift_token — one-time use, server-validated */
  gift_token: string;
  gifter_name: string;
}
