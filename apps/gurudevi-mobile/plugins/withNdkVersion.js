const { withProjectBuildGradle, createRunOncePlugin } = require('@expo/config-plugins');

const NDK_VERSION = '27.1.12297006';
const MARKER = '// @generated by withNdkVersion';

function withNdkVersion(config) {
  return withProjectBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('withNdkVersion requires a Groovy Android project build.gradle');
    }

    const assignment = `${MARKER}\nrootProject.ext.ndkVersion = '${NDK_VERSION}'`;
    const pattern = new RegExp(`${MARKER.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&')}[\\s\\S]*?rootProject\\.ext\\.ndkVersion = ['\"][^'\"]+['\"]`);

    let contents = cfg.modResults.contents;
    contents = pattern.test(contents) ? contents.replace(pattern, '') : contents;
    const rootPlugin = 'apply plugin: "expo-root-project"';
    contents = contents.includes(rootPlugin)
      ? contents.replace(rootPlugin, `${assignment}\n\n${rootPlugin}`)
      : `${assignment}\n\n${contents.trimStart()}`;
    cfg.modResults.contents = contents;

    return cfg;
  });
}

module.exports = createRunOncePlugin(withNdkVersion, 'withNdkVersion', '1.0.0');
