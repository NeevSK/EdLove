# Trübe-Art — Compile Commands Generator
# Generates compile_commands.json via CMake + Android NDK toolchain.
# Run from: packages/trube-art/native/
#
# USAGE: .\scripts\gen-compile-commands.ps1

param(
    [string]$BuildDir    = "$PSScriptRoot\..\native\build",
    [string]$OutputDir   = "$PSScriptRoot\..\native",
    [string]$NdkPath     = $env:ANDROID_NDK,
    [string]$Abi         = "arm64-v8a",
    [string]$ApiLevel    = "31"
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

# ---------------------------------------------------------------------------
# Validate NDK
# ---------------------------------------------------------------------------
if (-not $NdkPath) {
    # Try common Android Studio NDK locations
    $candidates = @(
        "$env:LOCALAPPDATA\Android\Sdk\ndk",
        "$env:USERPROFILE\AppData\Local\Android\Sdk\ndk"
    )
    foreach ($c in $candidates) {
        if (Test-Path $c) {
            $NdkPath = (Get-ChildItem $c | Sort-Object Name -Descending | Select-Object -First 1).FullName
            break
        }
    }
}

if (-not $NdkPath -or -not (Test-Path $NdkPath)) {
    Write-Error @"
Android NDK not found. Set ANDROID_NDK environment variable or pass -NdkPath.
Example: .\gen-compile-commands.ps1 -NdkPath 'C:\Users\you\AppData\Local\Android\Sdk\ndk\27.0.11902837'
"@
    exit 1
}

$ToolchainFile = Join-Path $NdkPath "build\cmake\android.toolchain.cmake"
if (-not (Test-Path $ToolchainFile)) {
    Write-Error "NDK toolchain file not found at: $ToolchainFile"
    exit 1
}

Write-Host "[Trübe-Art] Using NDK: $NdkPath" -ForegroundColor Cyan
Write-Host "[Trübe-Art] ABI: $Abi  |  API: $ApiLevel" -ForegroundColor Cyan

# ---------------------------------------------------------------------------
# Run CMake Configuration
# ---------------------------------------------------------------------------
$SourceDir = "$PSScriptRoot\..\native"

if (Test-Path $BuildDir) {
    Remove-Item $BuildDir -Recurse -Force
}
New-Item -ItemType Directory -Path $BuildDir -Force | Out-Null

$cmakeArgs = @(
    "-S", $SourceDir,
    "-B", $BuildDir,
    "-G", "Ninja",
    "-DCMAKE_TOOLCHAIN_FILE=$ToolchainFile",
    "-DANDROID_ABI=$Abi",
    "-DANDROID_PLATFORM=android-$ApiLevel",
    "-DANDROID=1",
    "-DCMAKE_BUILD_TYPE=Debug",
    "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON"
)

Write-Host "[Trübe-Art] Running CMake configuration..." -ForegroundColor Yellow
& cmake @cmakeArgs

if ($LASTEXITCODE -ne 0) {
    Write-Error "CMake configuration failed."
    exit 1
}

# ---------------------------------------------------------------------------
# Copy compile_commands.json to native/ for clangd
# ---------------------------------------------------------------------------
$src = Join-Path $BuildDir "compile_commands.json"
$dst = Join-Path $OutputDir "compile_commands.json"

if (Test-Path $src) {
    Copy-Item $src $dst -Force
    Write-Host "[Trübe-Art] compile_commands.json written to: $dst" -ForegroundColor Green
    Write-Host "[Trübe-Art] Reload your IDE / clangd for the changes to take effect." -ForegroundColor Green
} else {
    Write-Error "compile_commands.json was not generated by CMake."
    exit 1
}
