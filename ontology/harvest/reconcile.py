"""Merge harvested claims and flag conflicts against each other and against gurudevi.yaml.
Deterministic: same inputs, same bytes.

Inputs : out/claims-docs.yaml (from the document extraction), out/claims-code.yaml
         (from harvest_code.py), concepts.yaml (hand-written alignment of names to ontology
         concepts), ../gurudevi.yaml.
Outputs: out/conflicts.md (the report people read), out/concepts-seen.yaml (every name found,
         with its sources, so concepts.yaml can be extended).

Usage: python -I ontology/harvest/reconcile.py [ontology/harvest]
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

here = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent)
out = here / "out"
claims = []
for f in ("claims-docs.yaml", "claims-code.yaml"):
    claims += yaml.safe_load((out / f).read_text())["claims"]
unverified = [c for c in claims if c.get("verified") is False]
claims = [c for c in claims if c.get("verified") is not False]
concepts = yaml.safe_load((here / "concepts.yaml").read_text())
onto = yaml.safe_load((here.parent / "gurudevi.yaml").read_text())


def norm(s: str) -> str:
    s = re.sub(r"[^a-z0-9]", "", str(s).lower())
    return s[:-1] if s.endswith("s") and len(s) > 3 and not s.endswith("ss") else s


alias = {}  # normalised name -> concept
for concept, spec in concepts["concepts"].items():
    for name in [concept] + spec.get("names", []):
        alias[norm(name)] = concept
cap_alias = {norm(k): v for k, v in concepts.get("capacity_aliases", {}).items()}
state_alias = {norm(k): v for k, v in concepts.get("state_aliases", {}).items()}


def concept_of(subject: str) -> str | None:
    base = str(subject).split(".")[0]
    return alias.get(norm(base)) or alias.get(norm(subject))


def src(c) -> str:
    return f"`{c['doc']}:{c['line']}`"


onto_caps = list(onto["enums"]["Capacity"]["permissible_values"])
onto_states = {
    "Bond": list(onto["enums"]["BondState"]["permissible_values"]),
    "Enrollment": list(onto["enums"]["BondState"]["permissible_values"]),
    "Authority": list(onto["enums"]["AuthorityState"]["permissible_values"]),
}
onto_classes = [c for c, v in onto["classes"].items() if not v.get("mixin")]
report = ["# Harvest: conflicts and candidates", "",
          "Generated by `ontology/harvest/reconcile.py`. Do not edit; fix the sources or `concepts.yaml` and regenerate.", ""]

# ------------------------------------------------------------------ summary
by_kind = defaultdict(int)
docs = set()
for c in claims:
    by_kind[c["kind"]] += 1
    docs.add(c["doc"])
report += [f"{len(unverified)} document claims were left out because their quote was not found in the file.", ""]
report += [f"{len(claims)} claims from {len(docs)} files: " + ", ".join(f"{k} {v}" for k, v in sorted(by_kind.items())) + ".", ""]

# ------------------------------------------------------------------ 1. capacities
cap_sources = defaultdict(list)  # spelled capacity -> sources
for c in claims:
    if c["kind"] == "capacity_set":
        for v in c["value"] or []:
            if v != "...":
                cap_sources[str(v)].append(c)
    elif c["kind"] == "power" and isinstance(c["value"], dict) and c["doc"].endswith(".zmodel"):
        cap_sources[str(c["value"].get("who"))].append(c)
groups = defaultdict(dict)  # canonical -> spelled -> sources
for spelled, srcs in cap_sources.items():
    canon = cap_alias.get(norm(spelled), norm(spelled))
    groups[canon][spelled] = srcs
report += ["## 1. Capacities", "",
           f"The ontology has {len(onto_caps)}: {', '.join(onto_caps)}. The sources name {len(groups)} distinct capacities.", "",
           "| Capacity | Spellings found | In ontology | Sources (first 3) |", "| --- | --- | --- | --- |"]
for canon in sorted(groups, key=lambda k: (-sum(len(v) for v in groups[k].values()), k)):
    spells = groups[canon]
    allsrc = sorted({src(c) for v in spells.values() for c in v})
    inonto = "yes" if any(norm(o) == canon for o in onto_caps) else "**no**"
    flag = " ⚠ spelling" if len(spells) > 1 else ""
    report.append(f"| {canon}{flag} | {', '.join(f'`{s}`' for s in sorted(spells))} | {inonto} | {', '.join(allsrc[:3])}{' +' + str(len(allsrc) - 3) if len(allsrc) > 3 else ''} |")
report.append("")

# capacity lists that disagree with each other
lists = [c for c in claims if c["kind"] == "capacity_set"]
report += ["### Capacity lists, side by side", "",
           "Each row is one list a source gives. Lists that should be the same set but are not are the conflict.", "",
           "| Source | Subject | Values |", "| --- | --- | --- |"]
for c in sorted(lists, key=lambda c: (c["subject"], c["doc"], c["line"])):
    report.append(f"| {src(c)} | {c['subject']} | {', '.join(map(str, c['value'] or []))} |")
report.append("")

# ------------------------------------------------------------------ 2. names per concept
report += ["## 2. One concept, many names", "",
           "Names aligned to each ontology concept by `concepts.yaml`. More than one live name for the same thing is a conflict to settle.", ""]
names = defaultdict(lambda: defaultdict(list))
for c in claims:
    if c["kind"] in ("entity", "synonym", "relation", "state_set", "owner"):
        con = concept_of(c["subject"])
        if con:
            names[con][str(c["subject"]).split(".")[0]].append(c)
for con in sorted(concepts["concepts"]):
    spec = concepts["concepts"][con]
    found = names.get(con, {})
    tag = "in ontology" if con in onto_classes else "not in ontology yet"
    report += [f"### {con} ({tag})", "", spec.get("note", ""), ""]
    if not found:
        report += ["No source names it.", ""]
        continue
    report += ["| Name in source | Claims | Sources (first 3) |", "| --- | --- | --- |"]
    for n in sorted(found, key=lambda n: (-len(found[n]), n)):
        s = sorted({src(c) for c in found[n]})
        report.append(f"| `{n}` | {len(found[n])} | {', '.join(s[:3])}{' +' + str(len(s) - 3) if len(s) > 3 else ''} |")
    report.append("")

# ------------------------------------------------------------------ 3. state sets per concept
report += ["## 3. State lists that disagree", "",
           "For each concept, every state or status list a source gives, against the ontology. "
           "States are compared after `state_aliases` in `concepts.yaml`; case differences are flagged.", ""]
for con in sorted(concepts["concepts"]):
    sets = [c for c in claims if c["kind"] == "state_set" and concept_of(c["subject"]) == con
            and not re.search(r"(role|capacity|kind|type)$", str(c["subject"]), re.I)]
    if not sets:
        continue
    want = onto_states.get(con)
    report += [f"### {con}", ""]
    if want:
        report.append(f"Ontology: {', '.join(want)}")
        report.append("")
    report += ["| Source | Subject | Values | Differs from ontology |", "| --- | --- | --- | --- |"]
    for c in sorted(sets, key=lambda c: (c["doc"], c["line"])):
        vals = [str(v) for v in (c["value"] or [])]
        diff = ""
        if want:
            mapped = {state_alias.get(norm(v), norm(v)) for v in vals if v != "..."}
            extra = sorted(mapped - {norm(w) for w in want})
            case = any(v != v.lower() for v in vals)
            diff = "; ".join(x for x in [f"extra: {', '.join(extra)}" if extra else "", "UPPER CASE" if case else ""] if x) or "same or subset"
        report.append(f"| {src(c)} | {c['subject']} | {', '.join(vals)} | {diff} |")
    report.append("")

# ------------------------------------------------------------------ 4. transitions and powers in docs
report += ["## 4. Transitions and powers stated in docs", "",
           "What docs say changes a state, and who may do what. Compare with the lifecycles and `capacity-decides-powers` in `gurudevi.yaml`.", "",
           "| Source | Concept | Claim |", "| --- | --- | --- |"]
for c in sorted((c for c in claims if c["kind"] in ("transition", "power") and not c["doc"].endswith(".zmodel")),
                key=lambda c: (concept_of(c["subject"]) or "~", c["doc"], c["line"])):
    v = c["value"] if isinstance(c["value"], dict) else {"text": c["value"]}
    if c["kind"] == "transition":
        text = f"{v.get('from')} → {v.get('to')} by {v.get('by') or '?'} ({', '.join(map(str, v.get('who') or [])) or '?'})"
    else:
        text = f"{v.get('who')} {'may' if v.get('may', True) else 'may not'} {v.get('act')}" + (f" in {v.get('where')}" if v.get("where") else "")
    report.append(f"| {src(c)} | {concept_of(c['subject']) or c['subject']} | {text} |")
report.append("")

# ------------------------------------------------------------------ 5. rules in docs
report += ["## 5. Rules stated in docs", "",
           "Candidates for the rules section. None is added until Neev agrees.", "",
           "| Source | Subject | Rule |", "| --- | --- | --- |"]
for c in sorted((c for c in claims if c["kind"] == "rule"), key=lambda c: (c["doc"], c["line"])):
    report.append(f"| {src(c)} | {c['subject']} | {str(c['value']).replace('|', '/')[:180]} |")
report.append("")

# ------------------------------------------------------------------ 6. candidates
seen = defaultdict(set)
for c in claims:
    if c["kind"] == "entity":
        seen[str(c["subject"]).split(".")[0]].add(c["doc"])
aligned = set(alias)
cands = sorted(((n, s) for n, s in seen.items() if norm(n) not in aligned and len(s) >= 2), key=lambda x: (-len(x[1]), x[0]))
report += ["## 6. Things named in two or more sources, not aligned to any concept yet", "",
           "Candidates for the ontology, or names to add to `concepts.yaml`.", "",
           "| Name | Files | Example |", "| --- | --- | --- |"]
for n, s in cands:
    report.append(f"| `{n}` | {len(s)} | `{sorted(s)[0]}` |")
report.append("")

(out / "conflicts.md").write_text("\n".join(report) + "\n")
(out / "concepts-seen.yaml").write_text(yaml.safe_dump(
    {n: sorted(s) for n, s in sorted(seen.items())}, sort_keys=False, allow_unicode=True, width=200))
print(f"wrote {out / 'conflicts.md'}: {len(claims)} claims, {len(groups)} capacities, {len(cands)} unaligned candidates")
